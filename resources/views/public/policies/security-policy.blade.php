        <li>ตั้งรหัสผ่านที่คาดเดายาก ไม่ใช้ซ้ำกับระบบอื่น ไม่เปิดเผยรหัสผ่านแก่ผู้อื่น และเปลี่ยนรหัสผ่านเป็นระยะ</li>
