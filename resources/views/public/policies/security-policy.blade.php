    <p>คณะวิทยาศาสตร์การแพทย์ มหาวิทยาลัยพะเยา ตระหนักถึงความสำคัญของการรักษาความมั่นคงปลอดภัยเว็บไซต์ เพื่อปกป้องข้อมูลของผู้ใช้บริการ
        จากการถูกทำลาย ถูกแก้ไข หรือถูกเข้าถึงโดยผู้ไม่มีสิทธิ์ จึงกำหนดมาตรการตามพระราชบัญญัติการรักษาความมั่นคงปลอดภัยไซเบอร์ พ.ศ. 2562
        แนวปฏิบัติการรักษาความมั่นคงปลอดภัยเว็บไซต์ (Website Security Guideline) ของ สกมช. และมาตรฐานเว็บไซต์ภาครัฐ เวอร์ชัน 3.0 ดังนี้</p>

    <h2>1. มาตรการและวิธีการรักษาความมั่นคงปลอดภัย</h2>
    <ul>
        <li><strong>การเข้ารหัสการสื่อสาร</strong> เว็บไซต์ให้บริการผ่าน HTTPS ด้วยโปรโตคอล TLS 1.2 และ TLS 1.3
            ปิดการใช้งาน TLS 1.0/1.1 และใช้ใบรับรองอิเล็กทรอนิกส์ (SSL/TLS Certificate) จากผู้ให้บริการออกใบรับรองที่น่าเชื่อถือ
            ผู้ใช้บริการสังเกตได้จาก https:// และรูปแม่กุญแจที่แถบที่อยู่ของเบราว์เซอร์</li>
        <li><strong>การกำหนดค่าความปลอดภัยของเว็บไซต์</strong> ใช้ HTTP Security Headers เช่น HSTS, X-Content-Type-Options,
            X-Frame-Options และ Referrer-Policy และปิดกั้นการเข้าถึงไฟล์ระบบและไฟล์ตั้งค่าจากภายนอก</li>
        <li><strong>การยืนยันตัวตนและการควบคุมสิทธิ์</strong> ระบบบริหารจัดการเนื้อหาเข้าใช้ได้เฉพาะเจ้าหน้าที่ที่ได้รับมอบหมาย
            ผ่านระบบยืนยันตัวตนกลางของคณะฯ (MEDSCI ACC / Single Sign-On) และกำหนดสิทธิ์ตามหน้าที่</li>
        <li><strong>Auto Log off</strong> ระบบจะยุติการเข้าสู่ระบบอัตโนมัติเมื่อไม่มีการใช้งานเกิน 2 ชั่วโมง และคุกกี้ของระบบตั้งค่าแบบ Secure และ HttpOnly</li>
        <li><strong>การป้องกันการโจมตีทางเว็บ</strong> ป้องกันการปลอมแปลงคำขอข้ามเว็บไซต์ (CSRF) ตรวจสอบข้อมูลนำเข้า
            และจำกัดชนิดและขนาดของไฟล์ที่อัปโหลด</li>
        <li><strong>การปรับปรุงระบบและการสำรองข้อมูล</strong> ปรับปรุงเวอร์ชันระบบปฏิบัติการ PHP เฟรมเวิร์ก Laravel และแพ็กเกจที่ใช้อย่างสม่ำเสมอ
            และสำรองฐานข้อมูลและไฟล์เป็นประจำ</li>
        <li><strong>การเก็บรักษาข้อมูลจราจรทางคอมพิวเตอร์</strong> ไม่น้อยกว่า 90 วัน ตามประกาศกระทรวงดิจิทัลเพื่อเศรษฐกิจและสังคม
            เรื่อง หลักเกณฑ์การเก็บรักษาข้อมูลจราจรทางคอมพิวเตอร์ของผู้ให้บริการ</li>
    </ul>

    <h2>2. เทคโนโลยีเสริมที่ใช้ในการรักษาความมั่นคงปลอดภัย</h2>
    <ul>
        <li><strong>Firewall</strong> ระบบเครือข่ายของมหาวิทยาลัยพะเยาทำหน้าที่กลั่นกรองการเข้าถึงเครื่องแม่ข่าย ให้ผ่านได้เฉพาะช่องทางที่อนุญาต</li>
        <li><strong>การป้องกันมัลแวร์</strong> เครื่องแม่ข่ายติดตั้งโปรแกรมป้องกันไวรัสและปรับปรุงฐานข้อมูลอย่างสม่ำเสมอ</li>
        <li><strong>Cookies</strong> ใช้เท่าที่จำเป็นต่อการให้บริการ ตาม <a href="{{ route('pages.show', 'cookie-policy') }}">นโยบายคุกกี้</a></li>
    </ul>

