    <h2>1. คำนิยาม</h2>
    <ul>
        <li><strong>“คณะฯ” หรือ “ผู้ให้บริการ”</strong> หมายถึง คณะวิทยาศาสตร์การแพทย์ มหาวิทยาลัยพะเยา</li>
        <li><strong>“ผู้ใช้บริการ”</strong> หมายถึง บุคคลธรรมดาหรือนิติบุคคลที่เข้าชมหรือใช้บริการใด ๆ ผ่านเว็บไซต์ของคณะฯ</li>
        <li><strong>“บริการ”</strong> หมายถึง เว็บไซต์ ระบบสารสนเทศ เนื้อหา เอกสาร และบริการออนไลน์ (E-Service) ที่คณะฯ จัดให้มีขึ้น</li>
    </ul>

    <h2>2. ข้อกำหนดและการยอมรับข้อกำหนด</h2>
    <ol>
        <li>การเข้าใช้งานเว็บไซต์ถือว่าผู้ใช้บริการได้รับทราบและยอมรับข้อกำหนดฉบับนี้ รวมถึงนโยบายคุ้มครองข้อมูลส่วนบุคคล
            นโยบายคุกกี้ และนโยบายการรักษาความมั่นคงปลอดภัยเว็บไซต์ของคณะฯ</li>
        <li>บริการบางประเภทอาจมีข้อกำหนดเฉพาะเพิ่มเติม หากข้อกำหนดเฉพาะขัดแย้งกับข้อกำหนดฉบับนี้ ให้ใช้ข้อกำหนดเฉพาะสำหรับบริการนั้น</li>
        <li>คณะฯ อาจแก้ไขปรับปรุงข้อกำหนดนี้ได้ตามความเหมาะสม โดยจะแสดงวันที่ปรับปรุงล่าสุดไว้ที่หน้านี้</li>
    </ol>

