        <li>คณะฯ อาจหยุดให้บริการเป็นการชั่วคราวเพื่อบำรุงรักษาระบบ หรือเมื่อมีเหตุจำเป็นด้านความมั่นคงปลอดภัย</li>
        <li>คณะฯ มีสิทธิระงับการให้บริการแก่ผู้ใช้บริการรายใด หากการใช้บริการนั้นกระทบต่อผู้ใช้บริการอื่นหรือขัดต่อกฎหมาย</li>
