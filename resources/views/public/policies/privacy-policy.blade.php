        ระบบอื่นของคณะฯ หรือของมหาวิทยาลัยที่มีนโยบายเฉพาะ ให้เป็นไปตามนโยบายของระบบนั้น</p>

    <h2>2. คำนิยาม</h2>
    <ul>
        <li><strong>ข้อมูลส่วนบุคคล</strong> หมายถึง ข้อมูลเกี่ยวกับบุคคลธรรมดาซึ่งทำให้สามารถระบุตัวบุคคลนั้นได้ ไม่ว่าทางตรงหรือทางอ้อม
            แต่ไม่รวมถึงข้อมูลของผู้ถึงแก่กรรม</li>
